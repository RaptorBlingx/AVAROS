"""AVAROS data loader for PREVENTION platform.

Loads manufacturing KPI time-series data from JSON files into MongoDB.
Data files are exported from RENERYO (or generated by reneryo-data-generator)
and stored in the addon's data/ directory.

Follows PREVENTION's DataLoad ABC pattern (clean_data / load_data).
"""

import os
import urllib.parse

import pandas as pd
from core.initialization import DataLoad
from core.utils.datasources.mongo import mongo_utils
from pymongo import MongoClient


ADDON_NAME = "avaros"

DATA_FILES = [
    "energy_metrics.json",
    "production_metrics.json",
    "material_metrics.json",
    "carbon_metrics.json",
    "supplier_metrics.json",
]

DATABASES_TO_CLEAN = [
    "init_data",
    "prevention",
    ADDON_NAME,
    f"{ADDON_NAME}-results",
]

REQUIRED_COLUMNS = [
    "id",
    "metric_name",
    "asset_id",
    "timestamp",
    "value",
    "unit",
]

ANALYTICS_GOALS = [
    "ENERGY_ANOMALY_CHECK",
    "PRODUCTION_ANOMALY_CHECK",
    "MATERIAL_ANOMALY_CHECK",
    "CO2_ANOMALY_CHECK",
    "SUPPLIER_ANOMALY_CHECK",
    "ENERGY_DRIFT_CHECK",
    "PRODUCTION_DRIFT_CHECK",
    "MATERIAL_DRIFT_CHECK",
    "CO2_DRIFT_CHECK",
    "SUPPLIER_DRIFT_CHECK",
    "ENERGY_FORECAST",
    "PRODUCTION_FORECAST",
    "MATERIAL_FORECAST",
    "CO2_FORECAST",
    "SUPPLIER_FORECAST",
]

METADATA_DB_NAME = "wasabi"
RESULTS_DB_NAME = "wasabi-results"
DATASET_NAME = "AVAROS KPI Metrics"


class AvarosDataLoad(DataLoad):
    """Load AVAROS manufacturing KPI data into PREVENTION MongoDB."""

    def __init__(self):
        cwd = os.getcwd()
        self.data_path = f"{cwd}/addons/{ADDON_NAME}/data/"
        self.collection_name = "kpi_metrics"
        self.id_column = "id"
        self.date_column = "timestamp"

    def clean_data(self):
        """Drop all AVAROS-related MongoDB collections."""
        for db_name in DATABASES_TO_CLEAN:
            mongo_utils.drop_all_collections(db_name)
        _clean_avaros_metadata()

    def load_data(self):
        """Load all KPI JSON files into a single MongoDB collection."""
        print(f"[AVAROS] Loading data from {self.data_path}")

        frames = []
        for filename in DATA_FILES:
            filepath = self.data_path + filename
            if not os.path.exists(filepath):
                print(f"[AVAROS] WARNING: {filepath} not found, skipping")
                continue
            df = pd.read_json(filepath)
            print(f"[AVAROS] Loaded {len(df)} records from {filename}")

            if df.empty:
                continue

            missing_columns = [
                column for column in REQUIRED_COLUMNS if column not in df.columns
            ]
            if missing_columns:
                print(
                    "[AVAROS] WARNING: "
                    f"{filename} missing columns {missing_columns}, skipping",
                )
                continue

            frames.append(df)

        if not frames:
            print("[AVAROS] No non-empty valid data files found — addon will start without KPI records")
            return

        combined = pd.concat(frames, ignore_index=True)
        combined = combined.drop_duplicates(subset=self.id_column, keep="first")
        combined = combined.dropna(how="all")

        if combined.empty:
            print("[AVAROS] Combined KPI dataset is empty after cleanup")
            return

        combined = combined.sort_values(by=self.date_column)

        _insert_to_mongo(
            combined,
            id_column=self.id_column,
            collection_name=self.collection_name,
            db_name="init_data",
        )
        print(f"[AVAROS] Inserted {len(combined)} total records into MongoDB")


def _insert_to_mongo(
    df: pd.DataFrame,
    id_column: str,
    collection_name: str,
    db_name: str,
) -> None:
    """Insert a DataFrame into MongoDB with deduplication index."""
    client = MongoClient(
        f"mongodb://{mongo_utils.mongo_username}:"
        f"{urllib.parse.quote_plus(mongo_utils.mongo_pass)}"
        f"@{mongo_utils.mongo_host}:{int(mongo_utils.mongo_port)}/"
    )
    database = client[db_name]
    col = database[collection_name]
    col.create_index(id_column, unique=True)

    records = df.to_dict(orient="records")
    if records:
        col.insert_many(records)


def _clean_avaros_metadata() -> None:
    """Remove only metadata and result collections owned by this addon.

    PREVENTION keeps datasets, models, analyses, deployments, and result
    descriptors in its shared ``wasabi`` database. Leaving those records in
    place while replacing the input collection causes duplicate analytics and
    dangling deployments. The cleanup is deliberately scoped to AVAROS goal
    keys and the AVAROS dataset identity so other addons remain untouched.
    """
    client = MongoClient(
        f"mongodb://{mongo_utils.mongo_username}:"
        f"{urllib.parse.quote_plus(mongo_utils.mongo_pass)}"
        f"@{mongo_utils.mongo_host}:{int(mongo_utils.mongo_port)}/"
    )
    try:
        metadata = client[METADATA_DB_NAME]
        analyses = list(
            metadata["analysis"].find(
                {"analytics_goal": {"$in": ANALYTICS_GOALS}},
                {"_id": 1, "model": 1, "dataset": 1},
            ),
        )
        analysis_ids = [item["_id"] for item in analyses if item.get("_id")]
        model_ids = [item["model"] for item in analyses if item.get("model")]
        dataset_ids = [item["dataset"] for item in analyses if item.get("dataset")]

        deployments = list(
            metadata["deployment"].find(
                {"analysis": {"$in": analysis_ids}},
                {"_id": 1},
            ),
        ) if analysis_ids else []
        deployment_ids = [
            item["_id"] for item in deployments if item.get("_id")
        ]

        if deployment_ids:
            metadata["results"].delete_many(
                {"deployment": {"$in": deployment_ids}},
            )
            metadata["deployment"].delete_many(
                {"_id": {"$in": deployment_ids}},
            )
        if analysis_ids:
            metadata["analysis"].delete_many({"_id": {"$in": analysis_ids}})
        if model_ids:
            metadata["model"].delete_many({"_id": {"$in": model_ids}})

        dataset_filter = {
            "$or": [
                {"name": DATASET_NAME},
                {
                    "db_name": "init_data",
                    "collection_name": "kpi_metrics",
                },
            ],
        }
        if dataset_ids:
            dataset_filter["$or"].append({"_id": {"$in": dataset_ids}})
        metadata["dataset"].delete_many(dataset_filter)

        results_db = client[RESULTS_DB_NAME]
        for goal in ANALYTICS_GOALS:
            results_db[f"Results - {goal}"].drop()
    finally:
        client.close()
